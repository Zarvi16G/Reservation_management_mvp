#!/bin/bash
# Installed on the VPS as /usr/local/sbin/cloudflare-realip (root), run monthly by cron.
# Writes /etc/nginx/conf.d/cloudflare-realip.conf: behind Cloudflare's proxy every
# request comes from a Cloudflare IP; this tells Nginx to trust only those IPs and
# take the visitor's real IP from CF-Connecting-IP (the rate limits depend on it).
set -euo pipefail

out=/etc/nginx/conf.d/cloudflare-realip.conf
tmp=$(mktemp)
{
    echo "# Generated by /usr/local/sbin/cloudflare-realip on $(date -u +%F). Do not edit."
    for list in ips-v4 ips-v6; do
        curl -fsS "https://www.cloudflare.com/$list" | while read -r range; do
            [[ -n "$range" ]] && echo "set_real_ip_from $range;"
        done
    done
    echo "real_ip_header CF-Connecting-IP;"
} > "$tmp"

# Only replace the file if the download worked and Nginx accepts it.
if [[ $(grep -c set_real_ip_from "$tmp") -lt 10 ]]; then
    echo "Download looks wrong; keeping the current file" >&2
    rm -f "$tmp"
    exit 1
fi
install -m 644 "$tmp" "$out"
rm -f "$tmp"
nginx -t -q && systemctl reload nginx
